#!/bin/sh
set -eu

usage() {
    printf 'Usage: sh %s <version> | --check [tag]\n' "$0" >&2
    exit 1
}

sdk_dir=$(CDPATH= cd "$(dirname "$0")" && pwd)
version_file="$sdk_dir/VERSION"
go_file="$sdk_dir/internal/sdkuseragent/version.go"
mode=${1:-}

if [ "$mode" = "--check" ]; then
    shift
    [ "$#" -le 1 ] || usage
    version=$(cat "$version_file")
    if [ "$#" -eq 1 ] && [ "${1#v}" != "$version" ]; then
        printf 'Release tag %s does not match VERSION (%s)\n' "$1" "$version" >&2
        exit 1
    fi
else
    [ "$#" -eq 1 ] || usage
    version=${1#v}
fi

case "$version" in
    *[!0-9A-Za-z.+-]*) printf 'Invalid SDK version\n' >&2; exit 1 ;;
esac
if ! printf '%s\n' "$version" | grep -Eq '^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-[0-9A-Za-z-]+(\.[0-9A-Za-z-]+)*)?(\+[0-9A-Za-z-]+(\.[0-9A-Za-z-]+)*)?$'; then
    printf 'Invalid SDK version\n' >&2
    exit 1
fi

render_go() {
    printf '%s\n' '// Code generated by update-version.sh; DO NOT EDIT.' '' \
        'package sdkuseragent' '' "const Version = \"$version\""
}

if [ "$mode" = "--check" ]; then
    if ! render_go | cmp -s "$go_file" -; then
        printf 'Generated Go version does not match VERSION (%s)\n' "$version" >&2
        exit 1
    fi
else
    render_go > "$go_file"
    printf '%s\n' "$version" > "$version_file"
fi
